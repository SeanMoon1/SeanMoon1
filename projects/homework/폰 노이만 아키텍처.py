print("폰 노이만 아키텍처 ( Von Neumann Architecture )")
name = int(input("폰 노이만 아키텍처에 대해 알고 싶으신가요? (1: 예, 0: 아니오): "))
if name == 1:
    print("1. 폰 노이만 아키텍처는 컴퓨터 시스템의 기본 구조로, 프로그램과 데이터를 동일한 메모리 공간에 저장하고 처리하는 방식을 채택합니다.")
    print("2. 이 구조는 컴퓨터의 중앙 처리 장치(CPU), 메모리, 입력 장치, 출력 장치로 구성됩니다.")
    print("3. CPU는 명령어를 해석하고 실행하며, 메모리는 프로그램과 데이터를 저장합니다.")
    print("4. 입력 장치는 사용자로부터 데이터를 받아들이고, 출력 장치는 처리된 결과를 사용자에게 보여줍니다.")
    print("5. 폰 노이만 아키텍처의 특징은 프로그램과 데이터의 동일한 메모리 공간 사용, 순차적 실행, 저장 프로그램 개념, 중앙 처리 장치(CPU), 메모리, 입출력 장치로 구성됩니다.")
    print("6. 폰 노이만 아키텍처는 현대 컴퓨터 시스템의 기본 구조로, 대부분의 컴퓨터 시스템에서 사용되고 있습니다.")
else:
    print("폰 노이만 아키텍처에 대해 더 알고 싶으시면 1을 입력해주세요.")

for i in range(3):
    print("\n 폰 노이만 아키텍처의 장단점에 대해 알아보겠습니다.")
    print("1. 장점")
    print("2. 단점")
    choice = int(input("원하는 옵션을 선택하세요 (1 또는 2): "))
    if choice == 1:
        print("폰 노이만 아키텍처의 장점:")
        print("1. 단순성: 프로그램과 데이터가 동일한 메모리 공간에 저장되어 구조가 단순합니다.")
        print("2. 유연성: 프로그램을 수정하거나 업데이트할 수 있어 유연한 프로그래밍이 가능합니다.")
        print("3. 효율성: 명령어를 순차적으로 실행하여 CPU의 효율적인 사용이 가능합니다.")
        
    elif choice == 2:
        print("폰 노이만 아키텍처의 단점:")
        print("1. 병목 현상: 프로그램과 데이터가 동일한 메모리 공간에 저장되어 CPU와 메모리 간의 병목 현상이 발생할 수 있습니다.")
        print("2. 보안 취약성: 프로그램과 데이터가 동일한 메모리 공간에 저장되어 악성 코드가 프로그램을 수정하거나 데이터를 변경할 수 있는 보안 취약성이 존재합니다.")
        print("3. 성능 저하: 프로그램과 데이터가 동일한 메모리 공간에 저장되어 메모리 접근 속도가 느려질 수 있습니다.")
        break
    else:
        print("잘못된 입력입니다. 다시 시도해주세요.")
